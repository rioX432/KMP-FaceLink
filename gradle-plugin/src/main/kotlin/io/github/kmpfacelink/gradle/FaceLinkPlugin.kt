package io.github.kmpfacelink.gradle

import org.gradle.api.Plugin
import org.gradle.api.Project
import java.io.File

/**
 * Gradle plugin that registers the `faceLink` DSL extension with convention defaults
 * and wires model download tasks to the build lifecycle.
 *
 * Apply in a consumer project:
 * ```
 * plugins {
 *     id("io.github.rioX432.facelink")
 * }
 * ```
 */
public class FaceLinkPlugin : Plugin<Project> {

    override fun apply(project: Project) {
        val extension = project.extensions.create(
            EXTENSION_NAME,
            FaceLinkExtension::class.java,
        )
        applyConventionDefaults(extension)
        registerDownloadTask(project, extension)
    }

    private fun applyConventionDefaults(extension: FaceLinkExtension) {
        extension.faceEnabled.convention(DEFAULT_FACE_ENABLED)
        extension.handEnabled.convention(DEFAULT_HAND_ENABLED)
        extension.bodyEnabled.convention(DEFAULT_BODY_ENABLED)
        extension.precision.convention(DEFAULT_PRECISION)
        extension.outputDir.convention(DEFAULT_OUTPUT_DIR)
        extension.mediapipeVersion.convention(DEFAULT_MEDIAPIPE_VERSION)
    }

    private fun registerDownloadTask(project: Project, extension: FaceLinkExtension) {
        val downloadTask = project.tasks.register(
            DOWNLOAD_TASK_NAME,
            DownloadMediaPipeModelsTask::class.java,
        ) { task ->
            task.precision.set(extension.precision)
            task.version.set(extension.mediapipeVersion)
            task.outputDir.set(
                extension.outputDir.map { project.layout.projectDirectory.dir(it) },
            )
        }
        project.afterEvaluate {
            val models = buildModelList(extension)
            downloadTask.configure { task -> task.models.set(models) }
            writeGitIgnore(project, extension)
        }
        project.tasks.matching { it.name == "preBuild" }.configureEach {
            it.dependsOn(downloadTask)
        }
    }

    internal companion object {
        const val EXTENSION_NAME: String = "faceLink"
        const val DOWNLOAD_TASK_NAME: String = "downloadMediaPipeModels"
        const val DEFAULT_FACE_ENABLED: Boolean = true
        const val DEFAULT_HAND_ENABLED: Boolean = true
        const val DEFAULT_BODY_ENABLED: Boolean = false
        const val DEFAULT_PRECISION: String = "float16"
        const val DEFAULT_OUTPUT_DIR: String = "src/main/assets/models"
        const val DEFAULT_MEDIAPIPE_VERSION: String = "latest"

        internal fun buildModelList(
            extension: FaceLinkExtension,
        ): List<MediaPipeModelRegistry.ModelEntry> = buildList {
            if (extension.faceEnabled.get()) add(MediaPipeModelRegistry.faceLandmarker)
            if (extension.handEnabled.get()) add(MediaPipeModelRegistry.handLandmarker)
            if (extension.bodyEnabled.get()) add(MediaPipeModelRegistry.poseLandmarker)
        }

        internal fun writeGitIgnore(project: Project, extension: FaceLinkExtension) {
            val outputDir = File(project.projectDir, extension.outputDir.get())
            outputDir.mkdirs()
            val gitIgnore = File(outputDir, ".gitignore")
            if (!gitIgnore.exists()) {
                gitIgnore.writeText("# Auto-generated by KMP-FaceLink Gradle plugin\n*.task\n")
            }
        }
    }
}
